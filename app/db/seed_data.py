# Alias for backwards compatibility
SEED_PRODUCTS = PRODUCTS_DATA


async def seed_database(
    session: Optional[AsyncSession] = None,
    initial_qty: float = 50.0,
    force: bool = False,
) -> int:
    """Asynchronously populate database with PRODUCTS_DATA, stocks, and sample bars.

    If database already contains products, prints a warning and skips (unless force=True).
    """
    close_session_at_end = False
    if session is None:
        session = async_session_maker()
        close_session_at_end = True

    try:
        # 1. Check existing products count
        count_res = await session.execute(select(func.count(Product.id)))
        existing_count = count_res.scalar() or 0

        if existing_count > 0 and not force:
            print(f"⚠️  В базе данных уже есть {existing_count} товаров. Сидинг пропущен.")
            return existing_count

        print(f"🏢 Создание {len(SAMPLE_BARS)} тестовых кофеен...")
        # Check if bars exist
        for bar_data in SAMPLE_BARS:
            existing_bar = await session.execute(
                select(Bar).where(Bar.name == bar_data["name"])
            )
            if not existing_bar.scalar_one_or_none():
                session.add(
                    Bar(
                        name=bar_data["name"],
                        telegram_chat_id=bar_data["telegram_chat_id"],
                        is_active=bar_data["is_active"],
                    )
                )
        await session.flush()
        print("✅ Тестовые кофейни созданы.")

        print(f"📦 Заполнение каталога {len(PRODUCTS_DATA)} позициями...")
        products_to_add: List[Product] = []
        for idx, item in enumerate(PRODUCTS_DATA, start=1):
            sku = f"SKU-{idx:04d}"
            product = Product(
                sku=sku,
                name=item["name"],
                category=item["category"],
                unit=item["unit"],
                is_active=True,
            )
            stock = Stock(
                real_qty=initial_qty,
                reserved_qty=0.0,
            )
            product.stock = stock
            products_to_add.append(product)

        session.add_all(products_to_add)
        await session.commit()

        print("--------------------------------------------------")
        print(f"🎉 Успешно добавлено {len(products_to_add)} товаров (SKU-0001 ... SKU-{len(products_to_add):04d})")
        print(f"📊 Созданы остатки для каждого товара с real_qty={initial_qty:.1f}, reserved_qty=0.0, available_qty={initial_qty:.1f}")
        print("--------------------------------------------------")
        return len(products_to_add)

    finally:
        if close_session_at_end:
            await session.close()


